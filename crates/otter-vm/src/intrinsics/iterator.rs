/// §27.6.1 AsyncGeneratorValidate-shaped guard: a wrong receiver
/// REJECTS the returned promise instead of throwing (§27.6.1.2 step
/// 3 / AWAIT-shaped completions). `Ok(None)` means the receiver is a
/// genuine async generator and the caller should proceed.
fn async_generator_validate(
    ctx: &mut crate::NativeCtx<'_>,
    name: &'static str,
) -> Result<Option<Value>, crate::NativeError> {
    let this = *ctx.this_value();
    let ok = this
        .as_generator()
        .is_some_and(|g| g.is_async(ctx.interp_mut().gc_heap()));
    if ok {
        return Ok(None);
    }
    let Some(exec_ctx) = ctx.execution_context().cloned() else {
        return Err(crate::NativeError::TypeError {
            name,
            reason: "missing execution context".to_string(),
        });
    };
    ctx.with_turn_parts(|interp, stack| {
        let reason = interp
            .make_type_error_with_stack_roots(stack, "receiver is not an async generator object")
            .map_err(|_| crate::NativeError::TypeError {
                name,
                reason: "rejection allocation failed".to_string(),
            })?;
        let promise = crate::promise_dispatch::PromiseBuilder::with_context(exec_ctx)
            .rejected_stack_rooted(interp, stack, reason, &[&reason], &[])
            .map_err(|_| crate::NativeError::TypeError {
                name,
                reason: "rejection allocation failed".to_string(),
            })?;
        Ok(Some(Value::promise(promise)))
    })
}

/// Run one async-generator resumption method: §27.6.1 always returns
/// a promise, so a throw completion from the underlying machinery
/// (e.g. `throw` against a suspended-start or completed body) becomes
/// a rejection of the returned promise rather than a synchronous
/// throw.
fn async_generator_resumption(
    ctx: &mut crate::NativeCtx<'_>,
    args: &[Value],
    name: &'static str,
    resume: fn(Value) -> crate::GeneratorResumeKind,
) -> Result<Value, crate::NativeError> {
    if let Some(rejected) = async_generator_validate(ctx, name)? {
        return Ok(rejected);
    }
    let receiver = *ctx.this_value();
    let argument = args.first().copied().unwrap_or_else(Value::undefined);
    let method = move |ctx: &mut crate::NativeCtx<'_>, _args: &[Value]| {
        let Some(generator) = receiver.as_generator() else {
            return Err(crate::NativeError::TypeError {
                name,
                reason: "receiver is not an async generator object".to_string(),
            });
        };
        let Some(exec_ctx) = ctx.execution_context().cloned() else {
            return Err(crate::NativeError::TypeError {
                name,
                reason: "missing execution context".to_string(),
            });
        };
        ctx.with_turn_parts(|interp, stack| {
            interp
                .generator_resume_request(stack, &exec_ctx, generator, receiver, resume(argument))
                .map_err(|err| crate::native_function::vm_to_native_error(interp, err, name))
        })
    };
    match method(ctx, args) {
        Ok(value) => Ok(value),
        Err(err) => {
            let Some(exec_ctx) = ctx.execution_context().cloned() else {
                return Err(err);
            };
            let fallback_reason = format!("{err:?}");
            ctx.with_turn_parts(|interp, stack| {
                let reason = match interp.take_pending_uncaught_throw() {
                    Some(thrown) => thrown,
                    None => interp
                        .make_type_error_with_stack_roots(stack, &fallback_reason)
                        .map_err(|_| err)?,
                };
                let promise = crate::promise_dispatch::PromiseBuilder::with_context(exec_ctx)
                    .rejected_stack_rooted(interp, stack, reason, &[&reason], &[])
                    .map_err(|_| crate::NativeError::TypeError {
                        name,
                        reason: "rejection allocation failed".to_string(),
                    })?;
                Ok(Value::promise(promise))
            })
        }
    }
}

