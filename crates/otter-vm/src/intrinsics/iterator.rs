/// §27.1.2.4 `get %Iterator.prototype%[@@toStringTag]` — `"Iterator"`.
fn iterator_proto_to_string_tag_get(
    ctx: &mut crate::NativeCtx<'_>,
    _args: &[Value],
) -> Result<Value, crate::NativeError> {
    let tag = crate::string::JsString::from_str("Iterator", ctx.heap_mut()).map_err(|_| {
        crate::NativeError::TypeError {
            name: "Iterator.prototype[Symbol.toStringTag]",
            reason: "out of memory".to_string(),
        }
    })?;
    Ok(Value::string(tag))
}

/// §27.1.2.1.1 SetterThatIgnoresPrototypeProperties(thisValue,
/// %Iterator.prototype%, p, v) — writes land as own properties of the
/// receiver; assignments against the home prototype itself throw.
fn setter_ignoring_prototype_properties(
    ctx: &mut crate::NativeCtx<'_>,
    args: &[Value],
    key: crate::VmPropertyKey,
    name: &'static str,
) -> Result<Value, crate::NativeError> {
    let this_value = *ctx.this_value();
    if crate::abstract_ops::is_primitive(&this_value) {
        return Err(crate::NativeError::TypeError {
            name,
            reason: "this is not an object".to_string(),
        });
    }
    let value = args.first().cloned().unwrap_or(Value::undefined());
    let home = ctx
        .cx
        .interp
        .constructor_prototype_value("Iterator")
        .ok()
        .and_then(|v| v.as_object());
    let Some(this_obj) = this_value.as_object() else {
        // Exotic non-JsObject receivers (iterator handles, proxies)
        // have no own-property storage to write into; the spec's
        // CreateDataPropertyOrThrow degrades to a no-op here.
        return Ok(Value::undefined());
    };
    if let Some(home) = home
        && home == this_obj
    {
        return Err(crate::NativeError::TypeError {
            name,
            reason: "cannot assign on the home prototype".to_string(),
        });
    }
    let heap = ctx.heap_mut();
    let has_own = match &key {
        crate::VmPropertyKey::String(k) => {
            crate::object::get_own_descriptor(this_obj, heap, k).is_some()
        }
        crate::VmPropertyKey::Symbol(sym) => crate::object::has_own_symbol(this_obj, heap, *sym),
        _ => false,
    };
    if !has_own {
        match &key {
            crate::VmPropertyKey::String(k) => {
                crate::object::define_own_property(
                    this_obj,
                    heap,
                    k,
                    crate::object::PropertyDescriptor::data(value, true, true, true),
                );
            }
            crate::VmPropertyKey::Symbol(sym) => {
                crate::object::define_own_symbol_property(
                    this_obj,
                    heap,
                    *sym,
                    crate::object::PropertyDescriptor::data(value, true, true, true),
                );
            }
            _ => {}
        }
        return Ok(Value::undefined());
    }
    let exec_ctx =
        ctx.execution_context()
            .cloned()
            .ok_or_else(|| crate::NativeError::TypeError {
                name,
                reason: "missing execution context".to_string(),
            })?;
    match &key {
        crate::VmPropertyKey::String(k) => ctx.with_turn_parts(|interp, stack| {
            interp
                .ordinary_set_with_callable_setter(stack, &exec_ctx, this_obj, k, value, true)
                .map_err(|e| crate::native_function::vm_to_native_error(interp, e, name))
        })?,
        crate::VmPropertyKey::Symbol(sym) => ctx.with_turn_parts(|interp, stack| {
            interp
                .ordinary_set_symbol_with_callable_setter(
                    stack, &exec_ctx, this_obj, *sym, value, true,
                )
                .map_err(|e| crate::native_function::vm_to_native_error(interp, e, name))
        })?,
        _ => {}
    }
    Ok(Value::undefined())
}

/// §27.1.2.2 `set %Iterator.prototype%.constructor`.
fn iterator_proto_constructor_set(
    ctx: &mut crate::NativeCtx<'_>,
    args: &[Value],
) -> Result<Value, crate::NativeError> {
    setter_ignoring_prototype_properties(
        ctx,
        args,
        crate::VmPropertyKey::String("constructor"),
        "Iterator.prototype.constructor",
    )
}

/// §27.1.2.4 `set %Iterator.prototype%[@@toStringTag]`.
fn iterator_proto_to_string_tag_set(
    ctx: &mut crate::NativeCtx<'_>,
    args: &[Value],
) -> Result<Value, crate::NativeError> {
    let sym = ctx
        .cx
        .interp
        .well_known_symbols()
        .get(crate::symbol::WellKnown::ToStringTag);
    setter_ignoring_prototype_properties(
        ctx,
        args,
        crate::VmPropertyKey::Symbol(sym),
        "Iterator.prototype[Symbol.toStringTag]",
    )
}

/// Post-bootstrap pass that installs the symbol-keyed members of
/// `%Iterator.prototype%`: `@@iterator` (returns `this`) and
/// `@@toStringTag = "Iterator"`. Runs after the well-known symbol
/// table is materialised in the same phase that installs
/// `@@toStringTag` on TypedArray prototypes.
pub fn install_iterator_well_knowns_post_bootstrap(
    heap: &mut otter_gc::GcHeap,
    global: JsObject,
    well_known: &crate::symbol::WellKnownSymbols,
) -> Result<(), JsSurfaceError> {
    use crate::symbol::WellKnown;
    let iter_value = object::get(global, heap, "Iterator");
    let prototype = if let Some(ctor) = iter_value.as_ref().and_then(|v| v.as_native_function()) {
        ctor.own_property_descriptor(heap, "prototype")
            .ok()
            .flatten()
            .and_then(|d| match d.kind {
                crate::object::DescriptorKind::Data { value } => value.as_object(),
                _ => None,
            })
    } else if let Some(iterator_ctor) = iter_value.and_then(|v| v.as_object()) {
        object::get(iterator_ctor, heap, "prototype").and_then(|v| v.as_object())
    } else {
        None
    };
    let Some(prototype) = prototype else {
        return Ok(());
    };
    let mut proto_root = Value::object(prototype);
    let mut symbol_iter_root = Value::undefined();
    let mut tag_get_root = Value::undefined();
    let mut tag_set_root = Value::undefined();
    let mut ctor_get_root = Value::undefined();
    let mut ctor_set_root = Value::undefined();
    let mut roots = otter_gc::RootScope::new(heap);
    // SAFETY: all canonical slots precede the scope and remain stationary until
    // the complete Iterator.prototype surface is installed.
    unsafe {
        roots.add_value(&mut proto_root);
        roots.add_value(&mut symbol_iter_root);
        roots.add_value(&mut tag_get_root);
        roots.add_value(&mut tag_set_root);
        roots.add_value(&mut ctor_get_root);
        roots.add_value(&mut ctor_set_root);
    }
    symbol_iter_root = Value::native_function(
        native_static_with_value_roots(
            heap,
            "[Symbol.iterator]",
            0,
            iterator_proto_symbol_iterator,
            &[],
        )
        .map_err(|_| JsSurfaceError::OutOfMemory)?,
    );
    // §27.1.2.4 / §27.1.2.2 — `@@toStringTag` and `constructor` are
    // accessor properties whose setters write own properties on the
    // receiver (SetterThatIgnoresPrototypeProperties).
    let tag_sym = well_known.get(WellKnown::ToStringTag);
    tag_get_root = Value::native_function(
        native_static_with_value_roots(
            heap,
            "get [Symbol.toStringTag]",
            0,
            iterator_proto_to_string_tag_get,
            &[],
        )
        .map_err(|_| JsSurfaceError::OutOfMemory)?,
    );
    tag_set_root = Value::native_function(
        native_static_with_value_roots(
            heap,
            "set [Symbol.toStringTag]",
            1,
            iterator_proto_to_string_tag_set,
            &[],
        )
        .map_err(|_| JsSurfaceError::OutOfMemory)?,
    );
    ctor_get_root = Value::native_function(
        native_static_with_value_roots(
            heap,
            "get constructor",
            0,
            iterator_proto_constructor_get,
            &[],
        )
        .map_err(|_| JsSurfaceError::OutOfMemory)?,
    );
    ctor_set_root = Value::native_function(
        native_static_with_value_roots(
            heap,
            "set constructor",
            1,
            iterator_proto_constructor_set,
            &[],
        )
        .map_err(|_| JsSurfaceError::OutOfMemory)?,
    );
    let prototype = proto_root
        .as_object()
        .expect("Iterator.prototype remains rooted during symbol bootstrap");
    let iter_sym = well_known.get(WellKnown::Iterator);
    object::define_own_symbol_property_partial(
        prototype,
        heap,
        iter_sym,
        crate::object::PartialPropertyDescriptor {
            value: Some(symbol_iter_root),
            writable: Some(true),
            enumerable: Some(false),
            configurable: Some(true),
            ..Default::default()
        },
    );
    object::define_own_symbol_property_partial(
        prototype,
        heap,
        tag_sym,
        crate::object::PartialPropertyDescriptor {
            get: Some(tag_get_root),
            set: Some(tag_set_root),
            enumerable: Some(false),
            configurable: Some(true),
            ..Default::default()
        },
    );
    object::define_own_property_partial(
        prototype,
        heap,
        "constructor",
        crate::object::PartialPropertyDescriptor {
            get: Some(ctor_get_root),
            set: Some(ctor_set_root),
            enumerable: Some(false),
            configurable: Some(true),
            ..Default::default()
        },
    );
    Ok(())
}

/// Build the per-kind iterator prototypes
/// (`%ArrayIteratorPrototype%`, `%MapIteratorPrototype%`,
/// `%SetIteratorPrototype%`, `%StringIteratorPrototype%`,
/// `%RegExpStringIteratorPrototype%`) chained off `parent`
/// (`%IteratorPrototype%`). Called post-bootstrap once
/// `%IteratorPrototype%` is reachable.
pub fn build_builtin_iterator_prototypes_post_bootstrap(
    heap: &mut otter_gc::GcHeap,
    mut shape_root: object::ShapeHandle,
    parent: JsObject,
    well_known: &crate::symbol::WellKnownSymbols,
) -> Result<crate::bootstrap::BuiltinIteratorPrototypes, JsSurfaceError> {
    use crate::symbol::WellKnown;
    let mut parent_value = Value::object(parent);
    let mut array_root = Value::undefined();
    let mut map_root = Value::undefined();
    let mut set_root = Value::undefined();
    let mut string_root = Value::undefined();
    let mut regexp_string_root = Value::undefined();
    let mut helper_root = Value::undefined();
    let mut wrap_root = Value::undefined();
    let mut roots = otter_gc::RootScope::new(heap);
    // SAFETY: every canonical slot is declared before the scope and remains
    // stationary until the completed prototype set is returned.
    unsafe {
        roots.add_raw_slot(
            (&mut shape_root as *mut object::ShapeHandle).cast::<otter_gc::raw::RawGc>(),
        );
        roots.add_value(&mut parent_value);
        roots.add_value(&mut array_root);
        roots.add_value(&mut map_root);
        roots.add_value(&mut set_root);
        roots.add_value(&mut string_root);
        roots.add_value(&mut regexp_string_root);
        roots.add_value(&mut helper_root);
        roots.add_value(&mut wrap_root);
    }
    let tag_sym = well_known.get(WellKnown::ToStringTag);
    for (index, tag) in [
        "Array Iterator",
        "Map Iterator",
        "Set Iterator",
        "String Iterator",
        "RegExp String Iterator",
        "Iterator Helper",
    ]
    .into_iter()
    .enumerate()
    {
        let mut proto_root = Value::undefined();
        let mut tag_root = Value::undefined();
        let mut proto_scope = otter_gc::RootScope::new(heap);
        // SAFETY: both per-prototype canonical slots precede this nested scope
        // and are reloaded after every allocation.
        unsafe {
            proto_scope.add_value(&mut proto_root);
            proto_scope.add_value(&mut tag_root);
        }
        let mut no_extra_roots = |_visitor: &mut dyn FnMut(*mut otter_gc::raw::RawGc)| {};
        proto_root = Value::object(
            object::alloc_object_with_shape_roots(heap, shape_root, &mut no_extra_roots)
                .map_err(|_| JsSurfaceError::OutOfMemory)?,
        );
        let proto = proto_root
            .as_object()
            .expect("iterator prototype stays rooted after allocation");
        let parent = parent_value
            .as_object()
            .expect("Iterator.prototype stays rooted during bootstrap");
        object::set_prototype(proto, heap, Some(parent));
        tag_root = Value::string(
            crate::string::JsString::from_str(tag, heap)
                .map_err(|_| JsSurfaceError::OutOfMemory)?,
        );
        let proto = proto_root
            .as_object()
            .expect("iterator prototype stays rooted after tag allocation");
        object::define_own_symbol_property_partial(
            proto,
            heap,
            tag_sym,
            object::PartialPropertyDescriptor {
                value: Some(tag_root),
                writable: Some(false),
                enumerable: Some(false),
                configurable: Some(true),
                ..Default::default()
            },
        );
        let completed = Value::object(
            proto_root
                .as_object()
                .expect("iterator prototype stays rooted after tag definition"),
        );
        match index {
            0 => array_root = completed,
            1 => map_root = completed,
            2 => set_root = completed,
            3 => string_root = completed,
            4 => regexp_string_root = completed,
            5 => helper_root = completed,
            _ => unreachable!(),
        }
    }
    // §27.1.3.2 — `%WrapForValidIteratorPrototype%` carries no
    // `@@toStringTag` of its own.
    wrap_root = Value::object({
        let mut visit = |_visitor: &mut dyn FnMut(*mut otter_gc::raw::RawGc)| {};
        let proto = object::alloc_object_with_shape_roots(heap, shape_root, &mut visit)
            .map_err(|_| JsSurfaceError::OutOfMemory)?;
        let parent = parent_value
            .as_object()
            .expect("Iterator.prototype stays rooted during bootstrap");
        object::set_prototype(proto, heap, Some(parent));
        proto
    });
    let install_method = |heap: &mut otter_gc::GcHeap,
                          proto: JsObject,
                          name: &'static str,
                          length: u8,
                          call: crate::native_function::NativeFastFn,
                          label: &'static str|
     -> Result<(), JsSurfaceError> {
        let mut proto_root = Value::object(proto);
        let mut function_root = Value::undefined();
        let mut scope = otter_gc::RootScope::new(heap);
        // SAFETY: both canonical slots precede the nested scope. Defining the
        // property may allocate descriptor/shape storage after the native
        // function allocation, so the function itself must remain rooted too.
        unsafe {
            scope.add_value(&mut proto_root);
            scope.add_value(&mut function_root);
        }
        function_root = Value::native_function(
            native_static_with_value_roots(heap, name, length, call, &[])
                .map_err(|_| JsSurfaceError::OutOfMemory)?,
        );
        let proto = proto_root
            .as_object()
            .expect("iterator prototype stays rooted across method allocation");
        if !object::define_own_property(
            proto,
            heap,
            name,
            object::PropertyDescriptor::data(function_root, true, false, true),
        ) {
            return Err(JsSurfaceError::DefinePropertyFailed(label));
        }
        Ok(())
    };
    install_method(
        heap,
        regexp_string_root
            .as_object()
            .expect("RegExp iterator prototype is rooted"),
        "next",
        0,
        regexp_string_iterator_proto_next,
        "RegExpStringIteratorPrototype.next",
    )?;
    // §22.1.5.1 / §23.1.5.1 / §24.1.5.1 / §24.2.5.1 — each per-kind
    // built-in iterator prototype owns its `next`.
    install_method(
        heap,
        array_root
            .as_object()
            .expect("array iterator prototype is rooted"),
        "next",
        0,
        iterator_proto_next,
        "ArrayIteratorPrototype.next",
    )?;
    install_method(
        heap,
        map_root
            .as_object()
            .expect("map iterator prototype is rooted"),
        "next",
        0,
        iterator_proto_next,
        "MapIteratorPrototype.next",
    )?;
    install_method(
        heap,
        set_root
            .as_object()
            .expect("set iterator prototype is rooted"),
        "next",
        0,
        iterator_proto_next,
        "SetIteratorPrototype.next",
    )?;
    install_method(
        heap,
        string_root
            .as_object()
            .expect("string iterator prototype is rooted"),
        "next",
        0,
        iterator_proto_next,
        "StringIteratorPrototype.next",
    )?;
    // §27.1.2.1 — `%IteratorHelperPrototype%` owns `next` and `return`.
    install_method(
        heap,
        helper_root
            .as_object()
            .expect("iterator helper prototype is rooted"),
        "next",
        0,
        iterator_helper_proto_next,
        "IteratorHelperPrototype.next",
    )?;
    install_method(
        heap,
        helper_root
            .as_object()
            .expect("iterator helper prototype is rooted"),
        "return",
        1,
        iterator_helper_proto_return,
        "IteratorHelperPrototype.return",
    )?;
    // §27.1.3.2 — `%WrapForValidIteratorPrototype%` owns `next` and
    // `return`, both forwarding to the wrapped iterator.
    install_method(
        heap,
        wrap_root
            .as_object()
            .expect("wrap-for-valid iterator prototype is rooted"),
        "next",
        0,
        wrap_for_valid_iterator_next,
        "WrapForValidIteratorPrototype.next",
    )?;
    install_method(
        heap,
        wrap_root
            .as_object()
            .expect("wrap-for-valid iterator prototype is rooted"),
        "return",
        1,
        iterator_proto_return,
        "WrapForValidIteratorPrototype.return",
    )?;
    Ok(crate::bootstrap::BuiltinIteratorPrototypes {
        array: array_root
            .as_object()
            .expect("array iterator prototype is rooted"),
        map: map_root
            .as_object()
            .expect("map iterator prototype is rooted"),
        set: set_root
            .as_object()
            .expect("set iterator prototype is rooted"),
        string: string_root
            .as_object()
            .expect("string iterator prototype is rooted"),
        regexp_string: regexp_string_root
            .as_object()
            .expect("RegExp iterator prototype is rooted"),
        helper: helper_root
            .as_object()
            .expect("iterator helper prototype is rooted"),
        wrap_for_valid_iterator: wrap_root
            .as_object()
            .expect("wrap-for-valid iterator prototype is rooted"),
    })
}

fn iterator_receiver(
    ctx: &mut crate::NativeCtx<'_>,
    name: &'static str,
) -> Result<crate::IteratorHandle, crate::NativeError> {
    let this_value = *ctx.this_value();
    if let Some(h) = this_value.as_iterator() {
        return Ok(h);
    }
    if let Some(g) = this_value.as_generator() {
        let gen_value = Value::generator(g);
        let state = crate::IteratorState::Generator { handle: g };
        return ctx
            .alloc_iterator_state(state, &[&gen_value], &[])
            .map_err(|_| crate::NativeError::TypeError {
                name,
                reason: "iterator allocation failed".to_string(),
            });
    }
    // §7.4.4 GetIteratorDirect — the `Iterator.prototype.X` helpers
    // accept any Object receiver; `next` is read once here and NOT
    // checked for callability (a non-callable `next` throws when the
    // first step is driven, per IteratorNext).
    if !crate::abstract_ops::is_primitive(&this_value) {
        let exec_ctx =
            ctx.execution_context()
                .cloned()
                .ok_or_else(|| crate::NativeError::TypeError {
                    name,
                    reason: "missing execution context".to_string(),
                })?;
        let next_key = crate::VmPropertyKey::String("next");
        let outcome = ctx.with_turn_parts(|interp, stack| {
            interp
                .ordinary_get_value(stack, &exec_ctx, this_value, this_value, &next_key, 0)
                .map_err(|e| crate::native_function::vm_to_native_error(interp, e, name))
        })?;
        let next_method = match outcome {
            crate::VmGetOutcome::Value(v) => v,
            crate::VmGetOutcome::InvokeGetter { getter } => ctx.call(getter, this_value, &[])?,
        };
        let this_root = this_value;
        let state = crate::IteratorState::User {
            iterator: this_value,
            next_method: Some(next_method),
        };
        return ctx
            .alloc_iterator_state(state, &[&this_root, &next_method], &[])
            .map_err(|_| crate::NativeError::TypeError {
                name,
                reason: "iterator allocation failed".to_string(),
            });
    }
    Err(crate::NativeError::TypeError {
        name,
        reason: "this is not an object".to_string(),
    })
}

/// §27.1.4.x step 2 — every `Iterator.prototype.*` helper requires an
/// Object receiver; primitives throw TypeError before any argument
/// coercion or validation.
fn require_object_receiver(
    this_value: &Value,
    name: &'static str,
) -> Result<(), crate::NativeError> {
    if crate::abstract_ops::is_primitive(this_value) {
        return Err(crate::NativeError::TypeError {
            name,
            reason: "this is not an object".to_string(),
        });
    }
    Ok(())
}

/// §27.1.4.x — argument validation failures close the receiver
/// (IteratorClose with the validation error as completion) before the
/// iterator record is built. The original abrupt completion wins over
/// anything the close itself throws, per §7.4.9.
fn close_receiver_on_validation_failure(
    ctx: &mut crate::NativeCtx<'_>,
    this_value: Value,
    err: crate::NativeError,
) -> crate::NativeError {
    let Some(exec_ctx) = ctx.execution_context().cloned() else {
        return err;
    };
    ctx.with_turn_parts(|interp, stack| {
        let original_throw = interp.take_pending_uncaught_throw();
        let _ = interp.iterator_close_value_sync(stack, &exec_ctx, this_value);
        let _ = interp.take_pending_uncaught_throw();
        if let Some(value) = original_throw {
            interp.set_pending_uncaught_throw(value);
        }
    });
    err
}

/// Strict iterator receiver used by `%IteratorPrototype%.next/return/throw`.
/// Only accepts built-in iterator-shaped values (`Value::Iterator`,
/// `Value::Generator`); non-iterator receivers throw `TypeError` per
/// §27.1.5.1.2 step 2. The looser [`iterator_receiver`] used by the
/// helper terminals (map/filter/drop/take/forEach/…) would re-wrap an
